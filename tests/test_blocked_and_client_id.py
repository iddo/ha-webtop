async def test_real_client_sends_the_identification(hass: HomeAssistant) -> None:
    with patch("custom_components.webtop.auth.async_fetch_login_counter", AsyncMock(return_value=0)) as counter:
        default = await async_create_client(hass, "someone", "pw")
        custom = await async_create_client(hass, "someone", "pw", user_agent="my-experiment/1")
    try:
        assert isinstance(default, WebtopClient)
        assert default._http.headers["user-agent"] == DEFAULT_USER_AGENT
        assert custom._http.headers["user-agent"] == "my-experiment/1"
        assert default._http.headers["content-type"].startswith("application/json")  # pywebtop's own header stays
    finally:
        await default.close()
        await custom.close()
    # The login-counter request identifies itself the same way.
    assert [call.args[1] for call in counter.call_args_list] == [DEFAULT_USER_AGENT, "my-experiment/1"]


