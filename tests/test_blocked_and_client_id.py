def test_default_identification_says_what_the_client_is() -> None:
    manifest = json.loads((Path(__file__).parent.parent / "custom_components/webtop/manifest.json").read_text())
    assert manifest["version"] == INTEGRATION_VERSION
    assert DEFAULT_USER_AGENT.startswith(f"ha-webtop/{INTEGRATION_VERSION} ")
    assert "Home Assistant" in DEFAULT_USER_AGENT and "github.com/iddo/ha-webtop" in DEFAULT_USER_AGENT
    assert "Mozilla" not in DEFAULT_USER_AGENT  # it does not pose as a browser


