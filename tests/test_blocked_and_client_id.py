BLOCK_PAGE = (
    '<!DOCTYPE HTML PUBLIC "-//W3C//DTD HTML 4.01 Transitional//EN"><HTML><HEAD><TITLE>ERROR: The request could not '
    "be satisfied</TITLE></HEAD><BODY><H1>403 ERROR</H1><H2>The request could not be satisfied.</H2>Request blocked. "
    "Generated by cloudfront (CloudFront)</BODY></HTML>"
)
LOGIN_BLOCKED = WebtopLoginError(f"Login failed (403): {BLOCK_PAGE}")
REQUEST_BLOCKED = WebtopRequestError(f"POST /server/api/dashboard/InitDashboard failed (403): {BLOCK_PAGE}")
HOMEWORK = "sensor.nv_m_lvy_homework_today"
REFRESH = "button.webtop_dnh_lvy_refresh"
OPTIONS = {CONF_SCAN_INTERVAL: 30, CONF_NIGHT_PAUSE: False}


async def _setup(hass: HomeAssistant, config_entry, **options: Any) -> None:
    config_entry.add_to_hass(hass)
    hass.config_entries.async_update_entry(config_entry, options={**OPTIONS, **options})
    assert await hass.config_entries.async_setup(config_entry.entry_id)
    await hass.async_block_till_done()


async def _advance(hass: HomeAssistant, freezer: FrozenDateTimeFactory, **delta: float) -> None:
    freezer.tick(timedelta(**delta))
    async_fire_time_changed(hass)
    await hass.async_block_till_done(wait_background_tasks=True)


def _logins(fake_client) -> int:
    return sum(client.login_count for client in fake_client.created)


# --- recognizing a block ----------------------------------------------------
@pytest.mark.parametrize(
    ("error", "blocked"),
    [
        (LOGIN_BLOCKED, True),
        (REQUEST_BLOCKED, True),
        (WebtopRequestError("POST /x failed (403): <html><body>Access Denied</body></html>"), True),
        # The portal's own refusals are not a firewall block.
        (WebtopRequestError("POST /server/api/dashboard/InitDashboard failed (403): "), False),
        (WebtopRequestError("POST /x failed (401): "), False),
        (WebtopRequestError('POST /x failed (403): {"status":false,"errorDescription":"no permissions"}'), False),
        (WebtopLoginError("Login returned status=false. errorDescription=None, errorId=None"), False),
        (WebtopRequestError("POST /x failed (500): <html>Internal Server Error</html>"), False),
        (WebtopLoginError("Login request timed out: x"), False),
    ],
)
def test_is_firewall_block(error: Exception, blocked: bool) -> None:
    assert is_firewall_block(error) is blocked


def test_a_block_is_not_reported_as_a_wrong_password() -> None:
    assert login_failure_reason(LOGIN_BLOCKED) == "blocked"
    assert login_failure_reason(WebtopLoginError("Login failed (403): ")) == "invalid_auth"
    assert login_failure_reason(WebtopLoginError("Login failed (401): nope")) == "invalid_auth"


# --- setup and reauth forms -------------------------------------------------
async def test_setup_form_says_blocked_not_wrong_password(hass: HomeAssistant, fake_client) -> None:
    fake_client.responses["login"] = LOGIN_BLOCKED
    result = await hass.config_entries.flow.async_init(DOMAIN, context={"source": config_entries.SOURCE_USER})
    result = await hass.config_entries.flow.async_configure(
        result["flow_id"], {CONF_USERNAME: "parent", CONF_PASSWORD: "secret"}
    )
    assert result["type"] is FlowResultType.FORM and result["errors"] == {"base": "blocked"}


async def test_reauth_form_says_blocked(hass: HomeAssistant, fake_client, config_entry) -> None:
    await _setup(hass, config_entry)
    fake_client.responses["login"] = LOGIN_BLOCKED
    result = await config_entry.start_reauth_flow(hass)
    result = await hass.config_entries.flow.async_configure(result["flow_id"], {CONF_PASSWORD: "retyped"})
    assert result["errors"] == {"base": "blocked"}
    assert config_entry.data[CONF_PASSWORD] == "secret"  # nothing was saved


# --- a running integration that gets blocked --------------------------------
async def test_block_at_setup_fails_plainly_without_asking_for_a_password(
    hass: HomeAssistant, fake_client, config_entry, freezer: FrozenDateTimeFactory
) -> None:
    fake_client.responses["login"] = LOGIN_BLOCKED
    config_entry.add_to_hass(hass)
    assert not await hass.config_entries.async_setup(config_entry.entry_id)
    await hass.async_block_till_done()
    assert config_entry.state is ConfigEntryState.SETUP_ERROR  # not SETUP_RETRY: no retry every minute
    assert "firewall refused the connection" in (config_entry.reason or "")
    assert "not a password problem" in (config_entry.reason or "")
    assert hass.config_entries.flow.async_progress_by_handler(DOMAIN) == []  # no reauth prompt
    attempts = _logins(fake_client)
    await _advance(hass, freezer, minutes=10)
    assert _logins(fake_client) == attempts


async def test_block_while_running_backs_off_and_recovers(
    hass: HomeAssistant, fake_client, config_entry, freezer: FrozenDateTimeFactory, caplog: pytest.LogCaptureFixture
) -> None:
    await _setup(hass, config_entry)
    assert hass.states.get(HOMEWORK).state == "1"
    client = fake_client.created[0]
    client.responses["GetMenuCounters"] = REQUEST_BLOCKED  # a request every poll makes

    await _advance(hass, freezer, minutes=31)
    assert hass.states.get(HOMEWORK).state == "unavailable"
    assert "firewall refused the connection" in caplog.text and "Trying again in 1 h" in caplog.text
    assert hass.config_entries.flow.async_progress_by_handler(DOMAIN) == []  # still no password prompt
    assert _logins(fake_client) == 1  # and no pointless re-login into the firewall
    attempts = len([c for c in client.calls if c[0] == "GetMenuCounters"])

    def attempts_now() -> int:
        return len([c for c in client.calls if c[0] == "GetMenuCounters"])

    # Nothing is sent for an hour, then three hours, then six. (Home Assistant logs only the
    # first failure of a streak, so the waits are checked by what is actually sent.)
    await _advance(hass, freezer, minutes=50)
    assert attempts_now() == attempts
    await _advance(hass, freezer, minutes=15)
    assert attempts_now() == attempts + 1  # blocked again: now three hours
    await _advance(hass, freezer, hours=2, minutes=30)
    assert attempts_now() == attempts + 1
    await _advance(hass, freezer, minutes=35)
    assert attempts_now() == attempts + 2  # blocked again: now six hours
    await _advance(hass, freezer, hours=5, minutes=30)
    assert attempts_now() == attempts + 2
    assert _logins(fake_client) == 1 and hass.config_entries.flow.async_progress_by_handler(DOMAIN) == []

    # Once the firewall lets requests through again, the next attempt simply works.
    client.responses.pop("GetMenuCounters")
    await _advance(hass, freezer, minutes=35)
    assert attempts_now() == attempts + 3
    assert hass.states.get(HOMEWORK).state == "1"
    # ...and the back-off starts over from one hour.
    client.responses["GetMenuCounters"] = REQUEST_BLOCKED
    await _advance(hass, freezer, minutes=31)
    one_hour_notices = [r for r in caplog.records if "Trying again in 1 h" in r.getMessage()]
    assert len(one_hour_notices) == 2


async def test_refresh_button_tries_at_once_during_a_back_off(
    hass: HomeAssistant, fake_client, config_entry, freezer: FrozenDateTimeFactory
) -> None:
    await _setup(hass, config_entry)
    client = fake_client.created[0]
    client.responses["GetMenuCounters"] = REQUEST_BLOCKED
    await _advance(hass, freezer, minutes=31)
    assert hass.states.get(HOMEWORK).state == "unavailable"

    client.responses.pop("GetMenuCounters")
    await hass.services.async_call("button", "press", {"entity_id": REFRESH}, blocking=True)
    await hass.async_block_till_done(wait_background_tasks=True)
    assert hass.states.get(HOMEWORK).state == "1"


async def test_block_on_a_later_request_ends_the_poll_instead_of_trying_every_view(
    hass: HomeAssistant, fake_client, config_entry, freezer: FrozenDateTimeFactory
) -> None:
    await _setup(hass, config_entry)
    client = fake_client.created[0]
    client.responses["GetPupilLessonsAndHomework"] = WebtopRequestError(f"POST /x failed (403): {BLOCK_PAGE}")
    before = len(client.calls)
    await hass.services.async_call("button", "press", {"entity_id": REFRESH}, blocking=True)  # reads every view
    await hass.async_block_till_done(wait_background_tasks=True)
    made = [c[0] for c in client.calls[before:]]
    assert made.count("GetPupilLessonsAndHomework") == 1
    assert "GetPupilGrades" not in made and "get_messages_inbox" not in made
    assert hass.states.get(HOMEWORK).state == "unavailable"


