async def test_options_form_changes_and_clears_the_identification(
    hass: HomeAssistant, fake_client, config_entry
) -> None:
    one_child = {**DASHBOARD["data"], "childrens": DASHBOARD["data"]["childrens"][:1]}
    fake_client.responses["get_students"] = {"status": True, "data": one_child}
    await _setup(hass, config_entry)
    assert fake_client.created[-1]._http.headers["User-Agent"] == DEFAULT_USER_AGENT

    async def save(**fields: Any) -> dict[str, Any]:
        result = await hass.config_entries.options.async_init(config_entry.entry_id)
        schema = result["data_schema"].schema
        shown = next(key.description["suggested_value"] for key in schema if key == CONF_USER_AGENT)
        result = await hass.config_entries.options.async_configure(result["flow_id"], {**OPTIONS, **fields})
        await hass.async_block_till_done()
        assert result["type"] is FlowResultType.CREATE_ENTRY
        return {"shown": shown}

    assert (await save(**{CONF_USER_AGENT: "my-experiment/1"}))["shown"] == ""  # default shows as empty
    assert fake_client.created[-1]._http.headers["User-Agent"] == "my-experiment/1"  # reloaded with it
    assert (await save())["shown"] == "my-experiment/1"  # offered back; left out of the form = cleared
    assert config_entry.options[CONF_USER_AGENT] == ""
    assert fake_client.created[-1]._http.headers["User-Agent"] == DEFAULT_USER_AGENT


